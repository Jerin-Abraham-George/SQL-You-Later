/*
================================================================================================================
PROJECT: MAVEN FUZZY FACTORY
SECTION: CHANNEL PORTFOLIO MANAGEMENT ANALYSIS
================================================================================================================

CHANNEL PORTFOLIO MANAGEMENT ANALYSIS

This section evaluates how Maven Fuzzy Factory's marketing channels contribute
to website traffic and business growth. The analysis compares paid search
channels, examines device-level traffic and conversion performance, measures
the impact of bidding changes, and tracks the contribution of organic, direct,
and paid brand traffic.

COMMON USE CASES
    -- Compare traffic volumes across paid search channels.
    -- Monitor the growth and contribution of newly launched marketing channels.
    -- Evaluate channel performance across devices.
    -- Measure the impact of changes to paid search bids.
    -- Identify opportunities to diversify traffic sources and reduce reliance
       on a single acquisition channel.
    -- Support marketing budget allocation and channel investment decisions.

KEY TABLES
    -- website_sessions
    -- orders

NOTES
    -- All queries in this section are written for Microsoft SQL Server.
    -- Weekly queries use Sunday as the first day of the week.
================================================================================================================
*/

USE Ecommerce_DB;
GO


/*
================================================================================================================
ANALYSIS 01: WEEKLY PAID SEARCH CHANNEL PERFORMANCE
EMAIL DATE: NOVEMBER 29, 2012
FROM: TOM PARMESAN (MARKETING DIRECTOR)
SUBJECT: EXPANDED CHANNEL PORTFOLIO
================================================================================================================

BUSINESS REQUEST
With Gsearch performing well, Maven Fuzzy Factory launched Bsearch around
August 22. Compare weekly non-brand session volumes from Gsearch and Bsearch
to understand the contribution of the new paid search channel.

BUSINESS OBJECTIVE
Track the weekly traffic generated by each non-brand paid search channel
from the launch of Bsearch through November 29, 2012.
*/



    SELECT
        YEAR(created_at) AS yr,
        DATEPART(WEEK, created_at) AS week,
        MIN(CAST(created_at AS DATE)) AS first_session_date,
        COUNT(DISTINCT CASE
            WHEN utm_source = 'gsearch' THEN website_session_id
        END) AS gsearch_sessions,
        COUNT(DISTINCT CASE
            WHEN utm_source = 'bsearch' THEN website_session_id
        END) AS bsearch_sessions
    FROM website_sessions
    WHERE created_at >= '2012-08-22'
        AND created_at < '2012-11-30'
        AND utm_campaign = 'nonbrand'
        AND utm_source IN ('gsearch', 'bsearch')
    GROUP BY
        YEAR(created_at),
        DATEPART(WEEK, created_at)
    ORDER BY
        yr,
        week;


/*
================================================================================================================
ANALYSIS 02: MOBILE TRAFFIC CONTRIBUTION - BSEARCH VS. GSEARCH
EMAIL DATE: NOVEMBER 30, 2012
FROM: TOM PARMESAN (MARKETING DIRECTOR)
SUBJECT: COMPARING OUR CHANNELS
================================================================================================================

BUSINESS REQUEST
Compare the percentage of mobile traffic generated by the Bsearch non-brand
campaign with Gsearch. Tom requested aggregate results from August 22 through
November 29, 2012.

BUSINESS OBJECTIVE
Compare total sessions, mobile sessions, and mobile traffic share for the
two non-brand paid search channels.
*/


    SELECT
        utm_source,
        COUNT(DISTINCT website_session_id) AS total_sessions,
        COUNT(DISTINCT CASE
            WHEN device_type = 'mobile' THEN website_session_id
        END) AS mobile_sessions,
        FORMAT(
            CAST(COUNT(DISTINCT CASE
                WHEN device_type = 'mobile' THEN website_session_id
            END) AS FLOAT)
            / NULLIF(COUNT(DISTINCT website_session_id), 0),
            'P2'
        ) AS pct_mobile
    FROM website_sessions
    WHERE created_at >= '2012-08-22'
        AND created_at < '2012-11-30'
        AND utm_campaign = 'nonbrand'
        AND utm_source IN ('gsearch', 'bsearch')
    GROUP BY
        utm_source
    ORDER BY
        utm_source;


/*
================================================================================================================
ANALYSIS 03: NON-BRAND CONVERSION RATES BY CHANNEL AND DEVICE
EMAIL DATE: DECEMBER 1, 2012
FROM: TOM PARMESAN (MARKETING DIRECTOR)
SUBJECT: MULTI-CHANNEL BIDDING
================================================================================================================

BUSINESS REQUEST
Compare session-to-order conversion rates for Gsearch and Bsearch non-brand
campaigns, split by device type. Use August 22 through September 18, 2012,
excluding the special Gsearch campaign that began on September 19.

BUSINESS OBJECTIVE
Determine whether conversion performance differs by channel and device,
helping the marketing team assess whether both channels should use the same
bidding strategy.
*/


    SELECT
        ws.utm_source,
        ws.device_type,
        COUNT(DISTINCT ws.website_session_id) AS sessions,
        COUNT(DISTINCT o.order_id) AS orders,
        FORMAT(
            CAST(COUNT(DISTINCT o.order_id) AS FLOAT)
            / NULLIF(COUNT(DISTINCT ws.website_session_id), 0),
            'P2'
        ) AS session_to_order_conversion_rate
    FROM website_sessions AS ws
    LEFT JOIN orders AS o
        ON o.website_session_id = ws.website_session_id
    WHERE ws.created_at >= '2012-08-22'
        AND ws.created_at < '2012-09-19'
        AND ws.utm_campaign = 'nonbrand'
        AND ws.utm_source IN ('gsearch', 'bsearch')
    GROUP BY
        ws.utm_source,
        ws.device_type
    ORDER BY
        ws.utm_source,
        ws.device_type;


/*
================================================================================================================
ANALYSIS 04: WEEKLY CHANNEL TRAFFIC TRENDS AND BID CHANGE IMPACT
EMAIL DATE: DECEMBER 22, 2012
FROM: TOM PARMESAN (MARKETING DIRECTOR)
SUBJECT: IMPACT OF BID CHANGES
================================================================================================================

BUSINESS REQUEST
Bsearch non-brand bids were reduced on December 2. Compare weekly Gsearch
and Bsearch non-brand session volumes by device from November 4 through
December 22. Also calculate Bsearch sessions as a percentage of Gsearch
sessions for each device.

BUSINESS OBJECTIVE
Monitor channel traffic before and after the Bsearch bid reduction and
compare the relative contribution of Bsearch across desktop and mobile.
*/


    SELECT
        YEAR(created_at) AS yr,
        DATEPART(WEEK, created_at) AS week,
        MIN(CAST(created_at AS DATE)) AS first_session_date,

        COUNT(DISTINCT CASE
            WHEN utm_source = 'gsearch' AND device_type = 'desktop'
            THEN website_session_id
        END) AS g_desktop_sessions,

        COUNT(DISTINCT CASE
            WHEN utm_source = 'bsearch' AND device_type = 'desktop'
            THEN website_session_id
        END) AS b_desktop_sessions,

        FORMAT(
            CAST(COUNT(DISTINCT CASE
                WHEN utm_source = 'bsearch' AND device_type = 'desktop'
                THEN website_session_id
            END) AS FLOAT)
            / NULLIF(COUNT(DISTINCT CASE
                WHEN utm_source = 'gsearch' AND device_type = 'desktop'
                THEN website_session_id
            END), 0),
            'P2'
        ) AS bsearch_pct_of_gsearch_desktop,

        COUNT(DISTINCT CASE
            WHEN utm_source = 'gsearch' AND device_type = 'mobile'
            THEN website_session_id
        END) AS g_mobile_sessions,

        COUNT(DISTINCT CASE
            WHEN utm_source = 'bsearch' AND device_type = 'mobile'
            THEN website_session_id
        END) AS b_mobile_sessions,

        FORMAT(
            CAST(COUNT(DISTINCT CASE
                WHEN utm_source = 'bsearch' AND device_type = 'mobile'
                THEN website_session_id
            END) AS FLOAT)
            / NULLIF(COUNT(DISTINCT CASE
                WHEN utm_source = 'gsearch' AND device_type = 'mobile'
                THEN website_session_id
            END), 0),
            'P2'
        ) AS bsearch_pct_of_gsearch_mobile
    FROM website_sessions
    WHERE created_at >= '2012-11-04'
        AND created_at < '2012-12-23'
        AND utm_campaign = 'nonbrand'
        AND utm_source IN ('gsearch', 'bsearch')
    GROUP BY
        YEAR(created_at),
        DATEPART(WEEK, created_at)
    ORDER BY
        yr,
        week;


/*
================================================================================================================
ANALYSIS 05: MONTHLY TRAFFIC MIX AND CHANNEL DIVERSIFICATION
EMAIL DATE: DECEMBER 23, 2012
FROM: CINDY SHARP (CEO)
SUBJECT: SITE TRAFFIC BREAKDOWN
================================================================================================================

BUSINESS REQUEST
A potential investor wants to understand whether Maven Fuzzy Factory is
building brand momentum or continuing to rely on paid traffic. Report monthly
organic search, direct type-in, and paid brand sessions, and compare each
with paid non-brand sessions.

BUSINESS OBJECTIVE
Track the monthly contribution of organic, direct, and paid brand traffic
relative to paid non-brand traffic to assess channel diversification.

CHANNEL CLASSIFICATION
    -- Organic search: no UTM source and a recognized search-engine referrer.
    -- Paid non-brand: utm_campaign = 'nonbrand'.
    -- Paid brand: utm_campaign = 'brand'.
    -- Direct type-in: no UTM source and no referrer.

NOTE
The percentage metrics use paid non-brand sessions as the denominator.
They are comparison ratios, not shares of total website traffic.
*/


    SELECT
        YEAR(created_at) AS yr,
        MONTH(created_at) AS mo,

        COUNT(DISTINCT CASE
            WHEN channel_group = 'paid_nonbrand' THEN website_session_id
        END) AS nonbrand_sessions,

        COUNT(DISTINCT CASE
            WHEN channel_group = 'paid_brand' THEN website_session_id
        END) AS brand_sessions,

        FORMAT(
            CAST(COUNT(DISTINCT CASE
                WHEN channel_group = 'paid_brand' THEN website_session_id
            END) AS FLOAT)
            / NULLIF(COUNT(DISTINCT CASE
                WHEN channel_group = 'paid_nonbrand' THEN website_session_id
            END), 0),
            'P2'
        ) AS brand_pct_of_nonbrand,

        COUNT(DISTINCT CASE
            WHEN channel_group = 'direct_type_in' THEN website_session_id
        END) AS direct_sessions,

        FORMAT(
            CAST(COUNT(DISTINCT CASE
                WHEN channel_group = 'direct_type_in' THEN website_session_id
            END) AS FLOAT)
            / NULLIF(COUNT(DISTINCT CASE
                WHEN channel_group = 'paid_nonbrand' THEN website_session_id
            END), 0),
            'P2'
        ) AS direct_pct_of_nonbrand,

        COUNT(DISTINCT CASE
            WHEN channel_group = 'organic_search' THEN website_session_id
        END) AS organic_sessions,

        FORMAT(
            CAST(COUNT(DISTINCT CASE
                WHEN channel_group = 'organic_search' THEN website_session_id
            END) AS FLOAT)
            / NULLIF(COUNT(DISTINCT CASE
                WHEN channel_group = 'paid_nonbrand' THEN website_session_id
            END), 0),
            'P2'
        ) AS organic_pct_of_nonbrand

    FROM
    (
        SELECT
            website_session_id,
            created_at,
            CASE
                WHEN utm_source IS NULL
                    AND http_referer IN (
                        'https://www.gsearch.com',
                        'https://www.bsearch.com'
                    )
                    THEN 'organic_search'
                WHEN utm_campaign = 'nonbrand'
                    THEN 'paid_nonbrand'
                WHEN utm_campaign = 'brand'
                    THEN 'paid_brand'
                WHEN utm_source IS NULL
                    AND http_referer IS NULL
                    THEN 'direct_type_in'
            END AS channel_group
        FROM website_sessions
        WHERE created_at < '2012-12-23'
    ) AS sessions_w_channel_group
    GROUP BY
        YEAR(created_at),
        MONTH(created_at)
    ORDER BY
        yr,
        mo;
